#!/usr/bin/env node

/**
 * Add Image Format Metadata
 * 
 * Adds optimization metadata to existing experience images so they can use
 * AVIF and WebP formats.
 * 
 * Created by Denisse Maldonado
 */

require('dotenv').config({ 
  path: './environments/.env.development'
});

const Parse = require('parse/node');

// Initialize Parse
Parse.initialize(process.env.PARSE_APP_ID, process.env.PARSE_JAVASCRIPT_KEY, process.env.PARSE_MASTER_KEY);
Parse.serverURL = 'http://localhost:1337/parse';

async function addImageFormats() {
  console.log('🚀 Adding format metadata to Experience Images...');
  console.log('-----------------------------------\n');

  try {
    // Query experience images that have s3Key
    const query = new Parse.Query('ExperienceImage');
    query.equalTo('exists', true);
    query.exists('s3Key');
    query.limit(1000);
    
    const images = await query.find({ useMasterKey: true });
    
    console.log(`Found ${images.length} images to process\n`);

    let updatedCount = 0;

    for (const img of images) {
      const s3Key = img.get('s3Key');
      const fileName = img.get('fileName');
      
      // Skip if already has optimization data
      if (img.get('optimizedVariants') || img.get('optimizationMetadata')) {
        continue;
      }
      
      console.log(`Processing: ${fileName}`);
      
      // Extract base path and extension
      const match = s3Key.match(/^(.+)\.(jpg|jpeg|png|gif|webp)$/i);
      if (!match) {
        console.log(`  ⚠️  Unsupported format, skipping...`);
        continue;
      }
      
      const basePath = match[1];
      const extension = match[2].toLowerCase();
      
      // Create optimization metadata structure
      const optimizationMetadata = {
        formats: {
          avif: { 
            url: null,  // Will be generated by presigned URL
            s3Key: `${basePath}.avif`
          },
          webp: { 
            url: null,
            s3Key: `${basePath}.webp`
          },
          jpeg: { 
            url: null,
            s3Key: extension === 'jpeg' || extension === 'jpg' ? s3Key : `${basePath}.jpg`
          }
        },
        original: {
          s3Key: s3Key,
          format: extension
        }
      };
      
      // Also create optimizedVariants for compatibility
      const optimizedVariants = {
        avif: { 
          s3Key: `${basePath}.avif`,
          format: 'avif'
        },
        webp: { 
          s3Key: `${basePath}.webp`,
          format: 'webp'
        },
        jpeg: { 
          s3Key: extension === 'jpeg' || extension === 'jpg' ? s3Key : `${basePath}.jpg`,
          format: 'jpeg'
        }
      };
      
      img.set('optimizationMetadata', optimizationMetadata);
      img.set('optimizedVariants', optimizedVariants);
      
      await img.save(null, { useMasterKey: true });
      
      console.log(`  ✅ Format metadata added`);
      updatedCount++;
    }

    console.log('\n-----------------------------------');
    console.log('📊 Summary:');
    console.log(`✅ Updated: ${updatedCount} images`);
    console.log(`📁 Total checked: ${images.length}`);

  } catch (error) {
    console.error('❌ Error:', error.message);
    process.exit(1);
  }
}

// Run the script
addImageFormats()
  .then(() => {
    console.log('\n✅ Complete! Refresh browser to see optimized images.');
    process.exit(0);
  })
  .catch(error => {
    console.error('❌ Failed:', error);
    process.exit(1);
  });